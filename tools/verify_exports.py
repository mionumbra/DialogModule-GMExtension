#!/usr/bin/env python3
"""Verify that a built libdlgmod binary exports exactly the renamed symbols.

The build step injects ``renames.h`` (generated by gen_renames.py) into the
upstream sources.  This script checks the resulting DLL / .so / .dylib:

* every symbol from rename_map.json is exported,
* no unexpected symbols are exported,
* none of the original builtin-colliding names are exported unrenamed.

Exported names are read with a small built-in PE parser on Windows and with
``nm`` on Linux/macOS (always available on those CI runners).

Usage:
    python tools/verify_exports.py --binary dist/windows/libdlgmod.dll \
        --map .build/windows/rename_map.json
"""

from __future__ import annotations

import argparse
import json
import struct
import subprocess
import sys
from pathlib import Path


# --------------------------------------------------------------------------- #
# PE export table parser (no external dependencies)
# --------------------------------------------------------------------------- #
def _rva_to_offset(
    rva: int, sections: list[tuple[int, int, int, int]], headers_size: int
) -> int | None:
    if rva < headers_size:
        return rva
    for virt_addr, virt_size, raw_ptr, raw_size in sections:
        span = max(virt_size, raw_size)
        if virt_addr <= rva < virt_addr + span:
            return raw_ptr + (rva - virt_addr)
    return None


def pe_exports(path: Path) -> list[str]:
    data = path.read_bytes()
    if len(data) < 0x40 or data[:2] != b"MZ":
        raise ValueError(f"{path} is not a PE file")
    pe_offset = struct.unpack_from("<I", data, 0x3C)[0]
    if data[pe_offset : pe_offset + 4] != b"PE\0\0":
        raise ValueError(f"{path}: missing PE signature")

    coff = pe_offset + 4
    (
        _machine,
        num_sections,
        _timedate,
        _ptr_symtab,
        _num_symbols,
        opt_size,
        _characteristics,
    ) = struct.unpack_from("<HHIIIHH", data, coff)
    opt = coff + 20
    magic = struct.unpack_from("<H", data, opt)[0]
    if magic == 0x10B:  # PE32
        num_rva_offset = opt + 92
        data_dirs = opt + 96
    elif magic == 0x20B:  # PE32+
        num_rva_offset = opt + 108
        data_dirs = opt + 112
    else:
        raise ValueError(f"{path}: unsupported optional header magic 0x{magic:X}")

    num_dirs = struct.unpack_from("<I", data, num_rva_offset)[0]
    if num_dirs < 1:
        raise ValueError(f"{path}: no data directories")
    export_rva, export_size = struct.unpack_from("<II", data, data_dirs)
    if export_rva == 0 or export_size == 0:
        raise ValueError(f"{path}: no export directory")

    section_table = opt + opt_size
    sections: list[tuple[int, int, int, int]] = []
    for i in range(num_sections):
        off = section_table + i * 40
        (
            _name,
            virt_size,
            virt_addr,
            raw_size,
            raw_ptr,
        ) = struct.unpack_from("<8sIIII", data, off)
        sections.append((virt_addr, virt_size, raw_ptr, raw_size))
    headers_size = struct.unpack_from("<I", data, opt + 60)[0]  # SizeOfHeaders

    export_off = _rva_to_offset(export_rva, sections, headers_size)
    if export_off is None:
        raise ValueError(f"{path}: cannot map export directory RVA")

    (
        _characteristics,
        _timestamp,
        _major,
        _minor,
        _name_rva,
        _base,
        _num_functions,
        num_names,
        _addr_functions,
        addr_names,
        _addr_ordinals,
    ) = struct.unpack_from("<IIHHIIIIIII", data, export_off)

    names: list[str] = []
    names_off = _rva_to_offset(addr_names, sections, headers_size)
    if names_off is None:
        raise ValueError(f"{path}: cannot map export name array")
    for i in range(num_names):
        name_rva = struct.unpack_from("<I", data, names_off + i * 4)[0]
        name_off = _rva_to_offset(name_rva, sections, headers_size)
        if name_off is None:
            raise ValueError(f"{path}: cannot map export name #{i}")
        end = data.find(b"\0", name_off)
        names.append(data[name_off:end].decode("ascii", "replace"))
    return names


# --------------------------------------------------------------------------- #
# nm based readers (ELF / Mach-O)
# --------------------------------------------------------------------------- #
def _run_nm(args: list[str], path: Path) -> list[str]:
    try:
        proc = subprocess.run(
            ["nm", *args, str(path)],
            check=True,
            capture_output=True,
            text=True,
        )
    except FileNotFoundError:
        raise SystemExit(
            f"error: 'nm' not found; it is required to inspect {path.name}"
        ) from None
    except subprocess.CalledProcessError as exc:
        raise SystemExit(
            f"error: nm failed on {path}:\n{exc.stderr.strip()}"
        ) from None
    return proc.stdout.splitlines()


def elf_exports(path: Path) -> list[str]:
    names: list[str] = []
    for line in _run_nm(["-D", "--defined-only"], path):
        parts = line.split()
        if len(parts) < 3:
            continue
        symbol_type = parts[-2]
        name = parts[-1]
        if symbol_type in {"T", "t", "W", "w", "i"} and name:
            names.append(name)
    return names


def macho_exports(path: Path) -> list[str]:
    names: set[str] = set()
    for line in _run_nm(["-gU"], path):
        parts = line.split()
        if len(parts) < 3:
            continue
        symbol_type = parts[-2]
        name = parts[-1]
        if symbol_type not in {"T", "t", "W", "w"}:
            continue
        names.add(name[1:] if name.startswith("_") else name)
    return sorted(names)


# --------------------------------------------------------------------------- #
def detect_format(path: Path) -> str:
    head = path.read_bytes()[:4]
    if head[:2] == b"MZ":
        return "pe"
    if head == b"\x7fELF":
        return "elf"
    if head in {
        b"\xfe\xed\xfa\xce",
        b"\xce\xfa\xed\xfe",
        b"\xfe\xed\xfa\xcf",
        b"\xcf\xfa\xed\xfe",
        b"\xca\xfe\xba\xbe",
        b"\xbe\xba\xfe\xca",
    }:
        return "macho"
    raise ValueError(f"{path}: unrecognised binary format")


def collect_exports(path: Path, fmt: str) -> list[str]:
    if fmt == "pe":
        return pe_exports(path)
    if fmt == "elf":
        return elf_exports(path)
    if fmt == "macho":
        return macho_exports(path)
    raise ValueError(f"unsupported format: {fmt}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary", type=Path, required=True)
    parser.add_argument("--map", type=Path, required=True)
    parser.add_argument(
        "--format",
        choices=["auto", "pe", "elf", "macho"],
        default="auto",
    )
    parser.add_argument(
        "--allow-extra",
        action="store_true",
        help="do not fail on exports that are not listed in the rename map",
    )
    parser.add_argument(
        "--allow-missing",
        action="store_true",
        help="do not fail when a mapped export is missing from the binary",
    )
    args = parser.parse_args(argv)

    binary: Path = args.binary
    if not binary.is_file():
        print(f"error: binary not found: {binary}", file=sys.stderr)
        return 2
    map_path: Path = args.map
    if not map_path.is_file():
        print(f"error: rename map not found: {map_path}", file=sys.stderr)
        return 2

    rename_map = json.loads(map_path.read_text(encoding="utf-8"))
    expected = {fn["new"] for fn in rename_map["functions"]}
    old_collisions = {
        fn["old"] for fn in rename_map["functions"] if fn.get("builtin_collision")
    }

    fmt = detect_format(binary) if args.format == "auto" else args.format
    exports = collect_exports(binary, fmt)
    got = set(exports)
    missing = sorted(expected - got)
    extra = sorted(got - expected)
    unrenamed = sorted(got & old_collisions)

    print(f"format    : {fmt}")
    print(f"exports   : {len(got)}")
    print(f"expected  : {len(expected)}")
    for name in missing:
        print(f"  missing : {name}")
    for name in extra[:10]:
        print(f"  extra   : {name}")
    if len(extra) > 10:
        print(f"  ... {len(extra) - 10} more extra exports")
    for name in unrenamed:
        print(f"  UNRENAMED builtin collision: {name}")

    failed = False
    if unrenamed:
        failed = True
    if missing and not args.allow_missing:
        failed = True
    # ELF/Mach-O shared libraries also export internal C++/dependency symbols.
    # Only the expected exports and the absence of unrenamed builtin-collision
    # names matter there; PE DLLs stay strict because they only export
    # __declspec(dllexport) symbols.
    extra_allowed = args.allow_extra or fmt in {"elf", "macho"}
    if extra and not extra_allowed:
        failed = True

    if failed:
        print("verification FAILED", file=sys.stderr)
        return 1
    print("verification OK")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
